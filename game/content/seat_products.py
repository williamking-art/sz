#: 合法目标维（`RAW_DIMS` + 成品维）——映射表自校验用，避免拼错落到不存在的维
ALLOWED_DIMS = frozenset(RAW_DIMS) | {"绸", "布"}


def validate_map() -> List[str]:
    """返回**不合法的映射项**（目标维不在目录内）。空列表 = 通过。

    供测试与启动自检调用 —— 映射表若有拼写错误（如把「牲畜」写成别的），
    会落到不存在的维上。
    """
    bad = []
    for name, dims in SEAT_PRODUCT_MAP.items():
        for d in dims:
            if d not in ALLOWED_DIMS:
                bad.append("%s -> %s" % (name, d))
    return bad


